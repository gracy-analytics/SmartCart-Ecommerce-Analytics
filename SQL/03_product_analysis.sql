-- SECTION 1: PRODUCT PERFORMANCE
-- =====================================================

DESCRIBE smartcart.products;

DESCRIBE smartcart.order_items;

-- Business Question:
-- Which products have sold the highest number of units?

SELECT
    p.product_id,
    p.product_name,
    p.category,
    SUM(oi.quantity) AS total_units_sold
FROM smartcart.products p
JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
GROUP BY
    p.product_id,
    p.product_name,
    p.category
ORDER BY total_units_sold DESC
LIMIT 10;

-- Business Question:
-- Which products generate the highest revenue?

SELECT
    p.product_id,
    p.product_name,
    p.category,
    SUM(oi.quantity) AS total_units_sold,
    ROUND(SUM(oi.line_total_usd), 2) AS total_revenue_usd
FROM smartcart.products p
JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
GROUP BY
    p.product_id,
    p.product_name,
    p.category
ORDER BY total_revenue_usd DESC
LIMIT 10;

-- Business Question:
-- Which products generate the highest total profit?

SELECT
    p.product_id,
    p.product_name,
    p.category,
    SUM(oi.quantity) AS total_units_sold,
    ROUND(SUM(oi.line_profit_usd), 2) AS total_profit_usd
FROM smartcart.products p
JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
GROUP BY
    p.product_id,
    p.product_name,
    p.category
ORDER BY total_profit_usd DESC
LIMIT 10;

-- Business Question:
-- How many products generate an overall loss?

SELECT
    COUNT(*) AS loss_making_products
FROM (
    SELECT
        product_id,
        SUM(line_profit_usd) AS total_profit
    FROM smartcart.order_items
    GROUP BY product_id
    HAVING SUM(line_profit_usd) < 0
) AS product_losses;

-- Business Question:
-- Which product categories generate the highest total profit?

SELECT
    p.category,
    COUNT(DISTINCT p.product_id) AS total_products,
    ROUND(SUM(oi.line_total_usd), 2) AS total_revenue_usd,
    ROUND(SUM(oi.line_profit_usd), 2) AS total_profit_usd
FROM smartcart.products p
JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.category
ORDER BY total_profit_usd DESC;

-- Business Question:
-- What is the profit margin percentage for each product category?

SELECT
    p.category,
    ROUND(SUM(oi.line_total_usd), 2) AS total_revenue_usd,
    ROUND(SUM(oi.line_profit_usd), 2) AS total_profit_usd,
    ROUND(
        SUM(oi.line_profit_usd) /
        NULLIF(SUM(oi.line_total_usd), 0) * 100,
        2
    ) AS profit_margin_pct
FROM smartcart.products p
JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.category
ORDER BY profit_margin_pct DESC;

-- Business Question:
-- How many active and inactive products exist in each category?

SELECT
    category,
    is_active,
    COUNT(*) AS total_products
FROM smartcart.products
GROUP BY
    category,
    is_active
ORDER BY
    category,
    is_active;
    
    -- Business Question:
-- Do inactive products have any recorded sales?

SELECT
    p.product_id,
    p.product_name,
    p.category,
    p.is_active,
    COALESCE(SUM(oi.quantity), 0) AS total_units_sold,
    ROUND(COALESCE(SUM(oi.line_total_usd), 0), 2)
        AS total_revenue_usd
FROM smartcart.products p
LEFT JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
WHERE p.is_active = 'No'
GROUP BY
    p.product_id,
    p.product_name,
    p.category,
    p.is_active
ORDER BY total_revenue_usd DESC;

-- Business Question:
-- What is the total historical revenue generated by inactive products?

SELECT
    COUNT(DISTINCT p.product_id) AS inactive_products,
    SUM(oi.quantity) AS total_units_sold,
    ROUND(SUM(oi.line_total_usd), 2) AS total_revenue_usd,
    ROUND(SUM(oi.line_profit_usd), 2) AS total_profit_usd
FROM smartcart.products p
JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
WHERE p.is_active = 'No';

-- Business Question:
-- How do active and inactive products compare in historical sales performance?

SELECT
    p.is_active,
    COUNT(DISTINCT p.product_id) AS total_products,
    SUM(oi.quantity) AS total_units_sold,
    ROUND(SUM(oi.line_total_usd), 2) AS total_revenue_usd,
    ROUND(SUM(oi.line_profit_usd), 2) AS total_profit_usd
FROM smartcart.products p
LEFT JOIN smartcart.order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.is_active
ORDER BY p.is_active DESC;